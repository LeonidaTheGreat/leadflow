#!/usr/bin/env node
/**
 * generate-index-md.js — Auto-generate INDEX.md: a topic→file knowledge map.
 *
 * Scans all .md files in the project root, extracts their purpose from headers
 * and content hints, and builds a structured index agents can read to find
 * the right file for any topic.
 *
 * Called every heartbeat. Fully regenerated each time (no manual sections).
 */

const fs = require('fs')
const path = require('path')

const PROJECT_DIR = path.join(__dirname, '..')
const INDEX_PATH = path.join(PROJECT_DIR, 'INDEX.md')

// Files to skip (not useful as knowledge references)
const SKIP = new Set([
  'INDEX.md', 'LOG.md', 'package-lock.json', 'node_modules',
  '.git', '.next', '.vercel', '.claude'
])

function extractPurpose(filePath) {
  try {
    const content = fs.readFileSync(filePath, 'utf-8').slice(0, 2000)
    // Try first H1
    const h1 = content.match(/^#\s+(.+)/m)
    if (h1) return h1[1].trim()
    // Try HTML comment header
    const comment = content.match(/<!--\s*(.+?)\s*-->/)
    if (comment) return comment[1].trim().slice(0, 80)
    // First non-empty line
    const first = content.split('\n').find(l => l.trim().length > 5)
    return first ? first.trim().slice(0, 80) : '—'
  } catch {
    return '—'
  }
}

function isAutoGenerated(filePath) {
  try {
    const head = fs.readFileSync(filePath, 'utf-8').slice(0, 500)
    return /AUTO-GENERATED|auto-generated|Regenerated every heartbeat/i.test(head)
  } catch {
    return false
  }
}

function generateIndex() {
  const entries = []

  // Scan root .md files
  const rootFiles = fs.readdirSync(PROJECT_DIR)
    .filter(f => f.endsWith('.md') && !SKIP.has(f))
    .sort()

  for (const file of rootFiles) {
    const absPath = path.join(PROJECT_DIR, file)
    if (!fs.statSync(absPath).isFile()) continue
    entries.push({
      file,
      purpose: extractPurpose(absPath),
      autoGen: isAutoGenerated(absPath)
    })
  }

  // Scan docs/ subdirectory
  const docsDir = path.join(PROJECT_DIR, 'docs')
  if (fs.existsSync(docsDir)) {
    const walkDocs = (dir, prefix) => {
      for (const item of fs.readdirSync(dir)) {
        const abs = path.join(dir, item)
        const rel = prefix ? `${prefix}/${item}` : item
        if (fs.statSync(abs).isDirectory()) {
          walkDocs(abs, rel)
        } else if (item.endsWith('.md')) {
          entries.push({
            file: `docs/${rel}`,
            purpose: extractPurpose(abs),
            autoGen: isAutoGenerated(abs)
          })
        }
      }
    }
    walkDocs(docsDir, '')
  }

  // Build markdown
  let md = `<!-- AUTO-GENERATED — Regenerated every heartbeat. Do not edit manually. -->\n`
  md += `# Knowledge Index\n\n`
  md += `> Topic → file map. Read this first to find the right reference file.\n`
  md += `> Generated: ${new Date().toISOString()}\n\n`

  // Group: project root vs docs/
  const rootEntries = entries.filter(e => !e.file.startsWith('docs/'))
  const docEntries = entries.filter(e => e.file.startsWith('docs/'))

  md += `## Project Root\n\n`
  md += `| File | Purpose | Auto-gen? |\n`
  md += `|------|---------|----------|\n`
  for (const e of rootEntries) {
    md += `| \`${e.file}\` | ${e.purpose} | ${e.autoGen ? 'yes' : 'no'} |\n`
  }

  if (docEntries.length > 0) {
    md += `\n## Documentation (docs/)\n\n`
    md += `| File | Purpose |\n`
    md += `|------|---------|\n`
    for (const e of docEntries) {
      md += `| \`${e.file}\` | ${e.purpose} |\n`
    }
  }

  md += `\n## Quick Lookup\n\n`
  md += `| I need to know about... | Read... |\n`
  md += `|------------------------|---------|\n`
  md += `| Database schema, tables | \`SCHEMA.md\` |\n`
  md += `| Service classes, what exists | \`SERVICES.md\`, \`ARCHITECTURE.md\` |\n`
  md += `| API endpoints, routes | \`API.md\` |\n`
  md += `| Project rules, conventions | \`CLAUDE.md\` |\n`
  md += `| Agent-discovered gotchas | \`DISCOVERIES.md\` |\n`
  md += `| Use cases, product status | \`USE_CASES.md\` |\n`
  md += `| Test coverage | \`E2E_MAPPINGS.md\` |\n`
  md += `| PRD documents | \`PRD_INDEX.md\` |\n`

  return { md, count: entries.length }
}

function updateIndexMd() {
  const { md, count } = generateIndex()
  const existing = fs.existsSync(INDEX_PATH) ? fs.readFileSync(INDEX_PATH, 'utf-8') : ''
  if (md === existing) return { updated: false, count }
  fs.writeFileSync(INDEX_PATH, md)
  return { updated: true, count }
}

if (require.main === module) {
  const result = updateIndexMd()
  if (result.updated) {
    console.log(`✅ INDEX.md generated (${result.count} files indexed)`)
  } else {
    console.log(`ℹ️ INDEX.md unchanged (${result.count} files)`)
  }
}

module.exports = { updateIndexMd }
